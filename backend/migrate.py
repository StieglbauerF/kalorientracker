"""
Migration auf Mehrbenutzer-Betrieb und Datenschutz.

Befehle (die Ziel-Datenbank kommt aus DATABASE_URL):
  python migrate.py --status                  nur anzeigen, nichts ändern
  python migrate.py                           Tabellen, Spalten und ID-Vergabe reparieren
  python migrate.py --owner deine@mail.at     bisherige Daten diesem Konto zuordnen

Vor jeder Änderung wird die Ziel-Datenbank angezeigt und eine Bestätigung verlangt.
Das Skript ist idempotent: mehrfaches Ausführen schadet nicht.
"""
import argparse
import os
import sys

import main  # noqa: F401  importiert Engine und Modelle, legt fehlende Tabellen an
from sqlalchemy import inspect, text

TABLES_WITH_OWNER = ["user_settings", "foods", "meal_entries"]
USER_COLUMNS = {
    "privacy_accepted_at": "TIMESTAMP",
    "privacy_version": "VARCHAR",
}


def print_target() -> None:
    print(f"Ziel-Datenbank: {main.engine.url}")  # SQLAlchemy blendet das Passwort aus
    if not os.getenv("DATABASE_URL"):
        print("ACHTUNG: DATABASE_URL ist nicht gesetzt. Es wird die lokale SQLite-Datei verwendet!")


def confirm() -> None:
    answer = input("Fortfahren? Tippe 'ja' zur Bestätigung: ").strip().lower()
    if answer != "ja":
        sys.exit("Abgebrochen, es wurde nichts geändert.")


def show_status() -> None:
    with main.engine.connect() as conn:
        inspector = inspect(conn)
        user_columns = {c["name"] for c in inspector.get_columns("users")}
        count = conn.execute(text("SELECT COUNT(*) FROM users")).scalar()
        print(f"users: {count} Konto/Konten")
        if "privacy_accepted_at" in user_columns:
            pending = conn.execute(
                text("SELECT COUNT(*) FROM users WHERE privacy_accepted_at IS NULL")
            ).scalar()
            print(f"users: davon ohne Datenschutz-Zustimmung: {pending}")
        else:
            print("users: Spalten für Datenschutz fehlen (migrate.py ausführen)")

        for table in TABLES_WITH_OWNER:
            columns = {c["name"] for c in inspector.get_columns(table)}
            total = conn.execute(text(f"SELECT COUNT(*) FROM {table}")).scalar()
            if "user_id" not in columns:
                print(f"{table}: {total} Zeile(n), user_id-Spalte fehlt")
            else:
                orphans = conn.execute(
                    text(f"SELECT COUNT(*) FROM {table} WHERE user_id IS NULL")
                ).scalar()
                print(f"{table}: {total} Zeile(n), davon ohne Besitzer: {orphans}")


def add_missing_columns() -> None:
    with main.engine.begin() as conn:
        inspector = inspect(conn)

        user_columns = {c["name"] for c in inspector.get_columns("users")}
        for name, sql_type in USER_COLUMNS.items():
            if name not in user_columns:
                conn.execute(text(f"ALTER TABLE users ADD COLUMN {name} {sql_type}"))
                print(f"+ Spalte users.{name} angelegt")

        for table in TABLES_WITH_OWNER:
            columns = {c["name"] for c in inspector.get_columns(table)}
            if "user_id" not in columns:
                conn.execute(text(
                    f"ALTER TABLE {table} ADD COLUMN user_id INTEGER "
                    "REFERENCES users(id) ON DELETE CASCADE"
                ))
                print(f"+ Spalte {table}.user_id angelegt")

        # Indizes mit denselben Namen wie in main.py
        conn.execute(text(
            "CREATE UNIQUE INDEX IF NOT EXISTS ix_user_settings_user_id ON user_settings (user_id)"
        ))
        conn.execute(text("CREATE INDEX IF NOT EXISTS ix_foods_user_id ON foods (user_id)"))
        conn.execute(text("CREATE INDEX IF NOT EXISTS ix_meal_entries_user_id ON meal_entries (user_id)"))


def fix_id_generation() -> None:
    """
    Die alte Version hat user_settings.id mit default=1 angelegt. Dadurch gibt es in
    Postgres keine automatische ID-Vergabe, und jeder Insert ohne ID scheitert bzw.
    kollidiert mit der 1. Hier wird die Spalte auf automatische Vergabe (Identity)
    umgestellt und der Zähler auf den höchsten vorhandenen Wert + 1 gesetzt.
    """
    if main.engine.dialect.name != "postgresql":
        return  # SQLite vergibt IDs selbst korrekt
    with main.engine.begin() as conn:
        for table in TABLES_WITH_OWNER:
            info = conn.execute(text(
                "SELECT column_default, is_identity FROM information_schema.columns "
                "WHERE table_schema = current_schema() AND table_name = :t AND column_name = 'id'"
            ), {"t": table}).first()
            if info is not None and info[0] is None and info[1] == "NO":
                conn.execute(text(
                    f"ALTER TABLE {table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY"
                ))
                print(f"+ {table}.id auf automatische Vergabe umgestellt")
            conn.execute(text(
                f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                f"COALESCE((SELECT MAX(id) FROM {table}), 0) + 1, false)"
            ))
            print(f"ID-Zähler {table} synchronisiert")


def assign_owner(email: str) -> None:
    email = email.strip().lower()
    with main.engine.begin() as conn:
        row = conn.execute(text("SELECT id FROM users WHERE email = :email"), {"email": email}).first()
        if row is None:
            sys.exit(f"Kein Konto für {email}. Zuerst in der App registrieren.")
        uid = row[0]

        for table in TABLES_WITH_OWNER:
            if table == "user_settings":
                # Nach dem ersten Login legt das Frontend einen leeren Settings-Datensatz an.
                # Er wird nur ersetzt, wenn es noch alte Einstellungen ohne Besitzer gibt.
                # Bei einem erneuten Lauf bleiben die Einstellungen des Kontos unangetastet.
                legacy = conn.execute(text("SELECT COUNT(*) FROM user_settings WHERE user_id IS NULL")).scalar()
                if not legacy:
                    print("user_settings: keine alten Einstellungen mehr zuzuordnen")
                    continue
                conn.execute(text("DELETE FROM user_settings WHERE user_id = :uid"), {"uid": uid})
            result = conn.execute(
                text(f"UPDATE {table} SET user_id = :uid WHERE user_id IS NULL"), {"uid": uid}
            )
            print(f"{table}: {result.rowcount} Zeile(n) zugeordnet")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Migration auf Mehrbenutzer-Betrieb und Datenschutz")
    parser.add_argument("--owner", help="E-Mail des Kontos, das die bisherigen Daten erhält")
    parser.add_argument("--status", action="store_true", help="Nur den Zustand anzeigen, nichts ändern")
    args = parser.parse_args()

    print_target()
    if args.status:
        show_status()
        sys.exit(0)

    confirm()
    add_missing_columns()
    fix_id_generation()
    if args.owner:
        assign_owner(args.owner)
    print("\nFertig. Zustand danach:")
    show_status()
